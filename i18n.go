func T(key string, args ...any) string {
	langMap, ok := translations[CurrentLanguage]
	if !ok {
		langMap = translations["en"] // Default fallback to English
	}

	translated, ok := langMap[key]
	if !ok {
		// Fallback to English translation
		if engMap, ok := translations["en"]; ok {
			if engTrans, ok := engMap[key]; ok {
				translated = engTrans
			}
		}
		// If still not found, return the key itself
		if translated == "" {
			translated = key
		}
	}

	if len(args) > 0 {
		return fmt.Sprintf(translated, args...)
	}
	return translated
}
